// Rebuilds src/data/th08-data.ts from local, legally held TH08 v1.00d files.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseThbgmFmt } from './split-th08-bgm.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = join(root, 'reference/th08-original');
const outFile = join(root, 'src/data/th08-data.ts');

const H = {
  sprites: 0, scripts: 4, w: 12, h: 16, format: 20, colorkey: 24,
  nameoffset: 28, version: 40, memorypriority: 44,
  thtxoffset: 48, hasdata: 52, nextoffset: 56, size: 64
};

function stripAnmTextures(buf, fileName) {
  const parts = [];
  let offset = 0;
  let guard = 0;
  while (true) {
    if (guard++ > 64) throw new Error(`${fileName}: too many ANM entries`);
    const version = buf.readUInt32LE(offset + H.version);
    if (version !== 2 && version !== 3) {
      throw new Error(`${fileName}: entry at ${offset} has version ${version}`);
    }
    const nextoffset = buf.readUInt32LE(offset + H.nextoffset);
    const hasdata = buf.readUInt16LE(offset + H.hasdata);
    const thtxoffset = buf.readUInt32LE(offset + H.thtxoffset);
    const entryEnd = nextoffset ? offset + nextoffset : buf.length;
    const keepLen = hasdata && thtxoffset ? thtxoffset : entryEnd - offset;
    const nameoffset = buf.readUInt32LE(offset + H.nameoffset);
    if (nameoffset >= keepLen) throw new Error(`${fileName}: name outside kept range`);
    const entry = Buffer.from(buf.subarray(offset, offset + keepLen));
    entry.writeUInt32LE(0, H.thtxoffset);
    entry.writeUInt16LE(0, H.hasdata);
    entry.writeUInt32LE(nextoffset ? keepLen : 0, H.nextoffset);
    parts.push(entry);
    if (!nextoffset) break;
    offset = entryEnd;
  }
  const stripped = Buffer.concat(parts);
  verifyStrippedAnm(stripped, buf, fileName);
  return stripped;
}

function verifyStrippedAnm(stripped, original, fileName) {
  const walk = (b) => {
    const entries = [];
    let o = 0;
    while (true) {
      const name = readCString(b, o + b.readUInt32LE(o + H.nameoffset));
      entries.push({ sprites: b.readUInt32LE(o + H.sprites), scripts: b.readUInt32LE(o + H.scripts), name });
      const next = b.readUInt32LE(o + H.nextoffset);
      if (!next) return entries;
      o += next;
    }
  };
  if (JSON.stringify(walk(stripped)) !== JSON.stringify(walk(original))) {
    throw new Error(`${fileName}: stripped ANM metadata mismatch`);
  }
}

function readCString(buf, offset) {
  let end = offset;
  while (end < buf.length && buf[end] !== 0) end++;
  return buf.toString('latin1', offset, end);
}

const b64 = (name) => readFileSync(join(source, name)).toString('base64');
const anm = (name) => stripAnmTextures(readFileSync(join(source, `${name}.anm`)), name).toString('base64');

const ANM_FILES = [
  'title01', 'player00', 'ascii', 'text', 'front', 'times', 'capture',
  'enemy', 'etama',
  'stg1bg', 'stg1enm', 'stg1txt', 'eff01',
  'stg2bg', 'stg2enm', 'stg2txt', 'eff02',
  'face_rm00', 'face_yk00', 'face_st01', 'face_st01sp', 'face_st02', 'face_st02sp', 'face_cdbg'
];
const SHT_FILES = ['ply00a', 'ply00as'];

const bgmTracks = parseThbgmFmt(readFileSync(join(source, 'thbgm.fmt'))).map((t) => ({
  name: t.name,
  sampleRate: t.sampleRate,
  loopStartSample: t.loopStartBytes / 4,
  totalSamples: t.lengthBytes / 4
}));

const data = {
  stages: {
    1: {
      ecl: b64('ecldata1.ecl'),
      std: b64('stage1.std'),
      msg: b64('msg1a.dat'),
      enemyAnm: 'stg1enm',
      bulletAnm: 'etama',
      bgAnm: 'stg1bg',
      effectAnm: 'eff01',
      stdTxtAnm: 'stg1txt',
      faceAnm: 'face_st01',
      faceAnms: ['face_rm00', 'face_yk00', 'face_st01']
    },
    2: {
      ecl: b64('ecldata2.ecl'),
      std: b64('stage2.std'),
      msg: b64('msg2a.dat'),
      enemyAnm: 'stg2enm',
      bulletAnm: 'etama',
      bgAnm: 'stg2bg',
      effectAnm: 'eff02',
      stdTxtAnm: 'stg2txt',
      faceAnm: 'face_st02',
      faceAnms: ['face_rm00', 'face_yk00', 'face_st02']
    }
  },
  anm: Object.fromEntries(ANM_FILES.map((n) => [n, anm(n)])),
  sht: Object.fromEntries(SHT_FILES.map((n) => [n, b64(`${n}.sht`)])),
  bgm: bgmTracks
};

writeFileSync(
  outFile,
  '// Generated by scripts/generate-th08-data.mjs from reference/th08-original/.\n' +
  '// Do not edit by hand.\n' +
  `export const TH08_DATA = ${JSON.stringify(data, null, 1)} as const;\n`
);
console.log(`wrote ${outFile} (~${(JSON.stringify(data).length / 1024).toFixed(0)} KiB)`);
